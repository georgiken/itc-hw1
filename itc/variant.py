"""Параметры индивидуального варианта (раздел «Параметры варианта» задания)."""

S = 6


def params(s: int = S) -> dict:
    return {
        "s": s,
        "k": 5 - (s % 3),
        "M": 2 + (s % 3),
        "L": 3 + (s % 5),
        "d": 1 + (s % 3),
        "q": (2, 3, 5, 7)[s % 4],
        "eps": f"1e-{2 + (s % 3)}",
    }


def describe(s: int = S) -> str:
    p = params(s)
    return (f"Вариант s={p['s']}: k={p['k']}, M={p['M']}, L={p['L']}, "
            f"d={p['d']}, q={p['q']}, eps={p['eps']}")
